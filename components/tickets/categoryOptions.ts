/**
 * ชนิดสินค้าที่เลือกได้ในใบงาน — เฉพาะชนิดที่มีสินค้าอยู่จริง
 * (ร้านแจ้ง 27 พ.ย. 2569).
 *
 * ช่องสินค้าในใบงานดึงรายชื่อจากสต็อกอย่างเดียว ชนิดสินค้าที่ไม่มีสินค้าสักตัว
 * จึงเป็นทางตัน — เลือกแล้วช่องข้างล่างว่างเปล่า ไม่มีอะไรให้กรอกต่อ และไม่มี
 * อะไรบนจอบอกว่าทำไม ในระบบจริงมีแบบนี้อยู่สามชนิด (สปอยเลอร์ / ประกัน /
 * หน้ากาก) ค้างอยู่ในรายการตัวเลือกจากตอนตั้งระบบ
 *
 * ขาตรงข้ามก็เป็นทางตันเหมือนกัน: สินค้าที่ถูกนำเข้ามาพร้อมชนิดที่ไม่มีใครเพิ่ม
 * ลงรายการตัวเลือก (เช่น "จอ" ที่มาจากการนำเข้าหลาย SKU) จะขายไม่ได้เลย เพราะ
 * เลือกชนิดของมันไม่ได้ กฎนี้จึงตอบด้วยคำถามเดียว — "ชนิดนี้มีของให้ขายไหม" —
 * ไม่ใช่ "ชนิดนี้อยู่ในรายการตัวเลือกไหม"
 *
 * ผลคือ Book งาน กับ สต็อกสินค้า เห็นรายการชนิดสินค้าชุดเดียวกัน ซึ่งเป็นสิ่งที่
 * คนเปิดสองหน้านี้เทียบกันคาดหวังอยู่แล้ว
 */

/** เท่าที่กฎนี้ต้องรู้จากสินค้าหนึ่งตัวในสต็อก. */
export type CategorisedStock = { category?: string | null };

/**
 * `managed` คือรายการตัวเลือกที่ร้านดูแลเอง — ใช้กำหนด "ลำดับ" ที่คนคุ้นเคย
 * ส่วน `stock` เป็นตัวกำหนดว่าชนิดไหน "มีอยู่จริง"
 *
 * `current` คือชนิดที่บรรทัดนี้ถืออยู่แล้ว ต้องอยู่ในรายการเสมอ แม้ของจะหมด
 * ไปจากสต็อกแล้ว — `<select>` ที่ค่าไม่ตรงกับตัวเลือกไหนเลย จะแสดงตัวแรกแทน
 * ใบงานเก่าที่ลงชนิดไว้ว่า "หน้ากาก" จึงจะอ่านว่า "ฟิล์มกรองแสง" ทั้งที่ข้อมูล
 * ข้างในยังเป็นอย่างเดิม แล้วบันทึกทับทีเดียวก็เปลี่ยนของจริงไปเลย
 */
export function sellableCategories(
  managed: string[],
  stock: CategorisedStock[],
  current?: string,
): string[] {
  const existing = new Set(
    stock.map((s) => (s.category ?? '').trim()).filter((c): c is string => !!c),
  );
  const inOrder = managed.filter((c) => existing.has(c));
  // ชนิดที่มีของ แต่ไม่มีใครเพิ่มลงรายการตัวเลือก ต่อท้ายไว้ ไม่ใช่ทิ้ง
  const extras = [...existing]
    .filter((c) => !managed.includes(c))
    .sort((a, b) => a.localeCompare(b, 'th'));
  const all = [...inOrder, ...extras];
  return current && !all.includes(current) ? [current, ...all] : all;
}
