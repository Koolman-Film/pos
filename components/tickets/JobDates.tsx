import { fmtThaiDate } from '@/lib/domain/format';

/**
 * วันที่รับงาน และ วันที่ส่งงาน ของใบงานหนึ่งใบ บรรทัดเดียว (ร้านขอ 8 ต.ค. 2569).
 *
 * ทั้งสองหน้าที่ลิสต์ใบงาน — Book งาน และ งานล่าสุด บนแดชบอร์ด — เคยบอกวันเดียว
 * และคนละหน้าก็มีสิทธิ์เลือกคนละวันโดยไม่มีใครรู้ตัว คอมโพเนนต์นี้จึงถือทั้ง
 * ถ้อยคำและกติกาของบรรทัดนี้ไว้ที่เดียว
 *
 * สิ่งที่แก้ไปพร้อมกัน: หน้า Book งาน เขียนว่า "รับรถ" แล้วพิมพ์ `pickupDateObj`
 * ซึ่งคือ **วันที่ส่งงาน** ป้ายกับตัวเลขจึงพูดคนละเรื่องกันมาตลอด งานที่รับวัน
 * จันทร์ส่งวันพุธ ขึ้นในลิสต์ว่า "รับรถ วันพุธ"
 *
 * ขึ้นทั้งสองวันเสมอ แม้เป็นวันเดียวกัน — ลิสต์คือของที่คนกวาดสายตาลงมาเป็น
 * คอลัมน์ รูปแบบที่คงที่อ่านเร็วกว่ารูปแบบที่ฉลาดกว่า
 */
export function JobDates({
  dropOff,
  pickup,
  className = '',
}: {
  dropOff: Date | null | undefined;
  /** ใบที่ยังไม่ได้นัดวันส่ง — ขึ้นขีด ไม่ใช่เดาเอาว่าเป็นวันเดียวกับวันรับ */
  pickup: Date | null | undefined;
  className?: string;
}) {
  return (
    <span className={className}>
      รับงาน {fmtThaiDate(dropOff)} &middot; ส่งงาน {fmtThaiDate(pickup)}
    </span>
  );
}
