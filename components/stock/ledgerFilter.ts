/**
 * ตัวกรองของประวัติการเคลื่อนไหวสต็อก (ร้านขอ 17 พ.ย. 2569).
 *
 * ประวัติสต็อกคือสมุดบัญชีที่โตขึ้นเรื่อย ๆ และไม่มีวันเล็กลง หน้าจอเดิมมีแต่
 * ตัวกรอง "ประเภทการเคลื่อนไหว" ที่กรองอยู่บนแถวที่โหลดมาแล้วเท่านั้น คำถาม
 * ของคนที่มาตรวจสอบ — "ฟิล์มตัวนี้ที่สาขาลำปาง เดือนที่แล้วหายไปไหน" — จึงตอบ
 * ด้วยการเลื่อนหาเอาทีละหน้า
 *
 * กฎทั้งหมดอยู่ที่นี่ เพราะมันถูกใช้สองฝั่ง: หน้าเซิร์ฟเวอร์อ่านมันเพื่อสร้าง
 * คำถามไปยังฐานข้อมูล และหน้าจออ่านมันเพื่อรู้ว่าตอนนี้กรองอะไรอยู่ ถ้าสองฝั่ง
 * ตีความ URL ไม่ตรงกัน ตารางกับปุ่มตัวกรองจะพูดคนละเรื่อง
 *
 * กรองที่ฐานข้อมูล ไม่ใช่ที่หน้าจอ: ถ้ากรองบนแถวที่โหลดมาแล้ว ตัวกรองช่วงเวลา
 * จะค้นได้แค่ในกองล่าสุดที่หน้าจอบังเอิญถืออยู่ แล้วตอบว่า "ไม่มีรายการ" ทั้งที่
 * มีอยู่จริงถัดจากนั้นไปหนึ่งแถว ซึ่งเป็นคำตอบที่ผิดชนิดที่คนเชื่อ
 */

/**
 * ประเภทการเคลื่อนไหวทั้งหมดที่ระบบเขียนลงสมุด.
 *
 * เขียนไว้ตรง ๆ เพราะตัวเลือกต้องมีครบแม้ตารางกำลังถูกกรองจนเหลือประเภทเดียว
 * — ถ้าอ่านตัวเลือกจากแถวที่เห็นอยู่ พอกรอง "ปรับสต็อก" แล้ว รายการจะเหลือ
 * ปรับสต็อกอย่างเดียว และไม่มีทางเปลี่ยนไปดูประเภทอื่นได้โดยไม่ล้างตัวกรองก่อน
 *
 * หน้าจอรวมรายการนี้เข้ากับประเภทที่พบจริงในตาราง ประเภทใหม่ที่เพิ่มทีหลัง
 * จึงยังเลือกได้ แม้จะลืมมาเติมตรงนี้
 */
export const LEDGER_KINDS = [
  'ใบงาน',
  'ขายส่ง',
  'รับคืนขายส่ง',
  'เบิกใช้',
  'คืนจากใบเบิก',
  'รับเข้า',
  'ปรับสต็อก',
  'โอนออก',
  'โอนเข้า',
];

/** ชื่อพารามิเตอร์ใน URL — สั้น และขึ้นต้นด้วย l เพื่อไม่ชนกับตัวกรองอื่นของหน้า. */
export const LEDGER_PARAM = {
  shops: 'lshop',
  names: 'lname',
  cats: 'lcat',
  kinds: 'lkind',
  from: 'lfrom',
  to: 'lto',
} as const;

export type LedgerFilter = {
  /** รหัสสาขา — ว่าง = ทุกสาขาที่คนนี้เห็นได้. */
  shops: string[];
  /** ชื่อสินค้า ตามที่สมุดบัญชีบันทึกไว้ตอนนั้น. */
  names: string[];
  cats: string[];
  kinds: string[];
  /** `YYYY-MM-DD` — ว่าง = ไม่จำกัดด้านนั้น. */
  from: string;
  to: string;
};

export const EMPTY_LEDGER_FILTER: LedgerFilter = {
  shops: [],
  names: [],
  cats: [],
  kinds: [],
  from: '',
  to: '',
};

const DAY = /^\d{4}-\d{2}-\d{2}$/;

/**
 * หลายค่าคั่นด้วย `~` ไม่ใช่จุลภาค.
 *
 * ชื่อสินค้าของร้านมีจุลภาคอยู่ในชื่อได้ตามปกติ ("เต็มคัน: หน้า, ข้าง, หลัง")
 * ถ้าใช้จุลภาคเป็นตัวคั่น ชื่อเดียวจะกลายเป็นสามชื่อที่ไม่ตรงกับอะไรเลย แล้ว
 * ตารางจะว่างโดยที่ปุ่มยังบอกว่าเลือกไว้หนึ่งอย่าง
 */
const SEP = '~';

const list = (v: string | string[] | undefined): string[] => {
  const raw = Array.isArray(v) ? v.join(SEP) : (v ?? '');
  return [
    ...new Set(
      raw
        .split(SEP)
        .map((s) => s.trim())
        .filter(Boolean),
    ),
  ];
};

/**
 * วันที่จาก URL ที่เชื่อถือได้ — ว่าง ถ้าไม่ใช่วันที่จริง.
 *
 * ตรวจถึงขั้นว่ามีวันนั้นอยู่บนปฏิทินไหม ไม่ใช่แค่รูปร่างถูก: `2026-13-45`
 * มีรูปร่างครบทุกอย่าง แต่ถ้าส่งต่อไปเป็นช่วงเวลา ฐานข้อมูลจะตอบกลับมาเป็น
 * error แล้วทั้งหน้าจะพังเพราะคนพิมพ์ URL ผิดไปตัวเดียว
 */
const day = (v: string | string[] | undefined): string => {
  const raw = Array.isArray(v) ? v[0] : (v ?? '');
  if (!DAY.test(raw)) return '';
  const at = new Date(`${raw}T00:00:00Z`);
  return Number.isNaN(at.getTime()) || at.toISOString().slice(0, 10) !== raw ? '' : raw;
};

export function parseLedgerFilter(
  params: Record<string, string | string[] | undefined>,
): LedgerFilter {
  const from = day(params[LEDGER_PARAM.from]);
  const to = day(params[LEDGER_PARAM.to]);
  return {
    shops: list(params[LEDGER_PARAM.shops]),
    names: list(params[LEDGER_PARAM.names]),
    cats: list(params[LEDGER_PARAM.cats]),
    kinds: list(params[LEDGER_PARAM.kinds]),
    /*
      กรอกกลับหัว ก็อ่านว่าเป็นช่วงเดียวกัน.

      คนกรอกวันที่สองช่องนี้คนละครั้ง และพิมพ์ปลายทางก่อนได้ตามปกติ การคืน
      ตารางว่างเปล่าให้ตอนนั้น อ่านเหมือนว่า "ช่วงนี้ไม่มีรายการ" ซึ่งไม่จริง
    */
    from: from && to && to < from ? to : from,
    to: from && to && to < from ? from : to,
  };
}

/** ตอนนี้กรองอะไรอยู่หรือเปล่า — ตัวที่บอกว่าควรโชว์ปุ่มล้างตัวกรองไหม. */
export function isLedgerFiltered(f: LedgerFilter): boolean {
  return !!(f.shops.length || f.names.length || f.cats.length || f.kinds.length || f.from || f.to);
}

/** ค่าของตัวกรองในรูปแบบที่เขียนลง URL ได้ — ว่าง = ลบพารามิเตอร์นั้นทิ้ง. */
export function ledgerParamValue(values: string[]): string {
  return values.join(SEP);
}

/**
 * ช่วงเวลาเป็น instant ที่ถามฐานข้อมูลได้.
 *
 * วันของร้าน ไม่ใช่วันของเครื่องที่รันโค้ด — เซิร์ฟเวอร์เดินเวลา UTC รายการ
 * ที่บันทึกตอนสามทุ่มจึงเป็นของวันถัดไปถ้าอ่านด้วยนาฬิกาเครื่อง และจะหลุดออก
 * จากช่วงที่คนเลือก +07:00 ตายตัว: ไทยไม่มีเวลาออมแสง
 */
export function ledgerRange(f: LedgerFilter): { fromISO: string; toISO: string } {
  return {
    fromISO: f.from ? `${f.from}T00:00:00+07:00` : '',
    // ปลายทางรวมทั้งวัน — คนที่เลือกถึงวันที่ 17 หมายถึงรวมของวันที่ 17 ด้วย
    toISO: f.to ? `${f.to}T23:59:59.999+07:00` : '',
  };
}

/**
 * รหัสสินค้าที่อยู่ในชนิดที่เลือก — `null` = ไม่ได้กรองด้วยชนิดสินค้า.
 *
 * สมุดบัญชีไม่ได้เก็บชนิดสินค้าไว้ในแถวของมัน มันเก็บ `stock_id` กับชื่อ ณ
 * ตอนนั้น ชนิดสินค้าจึงต้องแปลงเป็นรายชื่อรหัสก่อน — ถามด้วยรหัสไม่ใช่ชื่อ
 * เพราะชื่อสินค้าของร้านยาวและเป็นภาษาไทย รายชื่อสองร้อยชื่อใน URL เดียวจะ
 * ยาวเกินกว่าที่ฐานข้อมูลยอมรับ
 *
 * สินค้าที่ถูกลบไปแล้วไม่มีรหัสเหลือให้จับคู่ มันจึงไม่ติดมากับการกรองตามชนิด
 * ซึ่งตรงกับความจริง: ระบบไม่รู้แล้วว่าของชิ้นนั้นเคยเป็นชนิดอะไร
 */
export function ledgerStockIds(
  f: LedgerFilter,
  products: { id: number; category: string }[],
): number[] | null {
  if (!f.cats.length) return null;
  return products.filter((p) => f.cats.includes(p.category)).map((p) => p.id);
}
