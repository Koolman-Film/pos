/**
 * ค่าใช้จ่ายแถวไหนที่ "เงินออกจากบัญชีไปแล้วจริง".
 *
 * คำถามเดียวนี้ถูกตอบอยู่สองที่ ด้วยคำตอบคนละแบบ และนั่นคือเหตุที่ยอดเงินสดย่อย
 * บนหน้า ค่าใช้จ่าย กับบนแดชบอร์ด อ่านได้คนละตัวเลข (ร้านเจอ 31 ต.ค. 2569):
 * ฝั่งการจัดการเงินถามทั้งสถานะและวันที่จ่าย ส่วนการ์ดเงินสดย่อยถามแค่สถานะ
 * แถวที่ติด "จ่ายแล้ว" แต่ไม่มีวันที่ จึงถูกนับข้างเดียว
 *
 * ทำไมต้องมีวันที่ด้วย: ทุกยอดคงเหลือสร้างจากกระแสเงินที่เรียงตามเวลา — บัญชี
 * นับเฉพาะเงินที่เดินหลังวันเปิดบัญชี และรายงานการเงินรายวันตัดยอด ณ สิ้นวัน
 * เงินก้อนที่ไม่รู้ว่าออกไปวันไหน วางลงในเส้นเวลาไม่ได้ และการเดาให้มันว่าเป็น
 * วันนี้ คือการย้ายเงินข้ามเดือนโดยไม่มีใครตัดสินใจ
 *
 * แถวแบบนั้นจึงไม่ถูกนับทั้งสองที่ และการ์ดเงินสดย่อยขึ้นคำเตือนแทน — เงินที่
 * หายไปจากยอดอย่างเงียบ ๆ แย่กว่ายอดที่บอกว่าตัวเองไม่ครบ
 */

export const EXPENSE_PAID = 'จ่ายแล้ว';

/** เท่าที่ยอดคงเหลือต้องรู้เกี่ยวกับค่าใช้จ่ายหนึ่งแถว. */
export type MoneyMovingExpense = {
  status: string;
  /**
   * วันที่จ่ายจริง — ว่างเมื่อยังไม่จ่าย หรือจ่ายแล้วแต่ไม่ได้ลงวันที่ไว้.
   *
   * รับได้ทั้ง string และ Date เพราะแต่ละหน้าจอถือมันคนละรูป — หน้า ค่าใช้จ่าย
   * แปลงเป็น Date ไว้ให้ช่องแก้วันที่ใช้ ส่วนฝั่งโหลดข้อมูลเงินถือเป็น ISO ตาม
   * ที่อ่านมา กฎต้องเป็นกฎเดียว ไม่ใช่สองกฎเพราะรูปข้อมูลต่างกัน
   */
  paidAt: string | Date | null | undefined;
};

/** จ่ายออกไปแล้ว และรู้ว่าวันไหน — เงื่อนไขเดียวกับที่ `loadMoneyData` ใช้. */
export function movesMoney(e: MoneyMovingExpense): boolean {
  return e.status === EXPENSE_PAID && !!e.paidAt;
}

/** ติด "จ่ายแล้ว" ไว้ แต่ไม่มีวันที่ — เงินที่ไม่มียอดไหนนับได้. */
export function paidWithoutDate(e: MoneyMovingExpense): boolean {
  return e.status === EXPENSE_PAID && !e.paidAt;
}
