/**
 * ปริมาณต่อหน่วย — ม้วนละกี่ตารางฟุต และกฎการหารที่ตามมา (migration 0088).
 *
 * ฟิล์มขายเป็นม้วน แต่ของที่คืนกลับมาวัดเป็นตารางฟุต และม้วนละไม่เท่ากัน —
 * 500 บ้าง 250 บ้าง คืนมา 300 ตร.ฟ. จากม้วนละ 500 คือ 0.6 ม้วน จากม้วนละ 250
 * คือ 1.2 ม้วน ตัวเลขเดียวกัน ความหมายต่างกันสองเท่า
 *
 * ความรู้นี้เคยอยู่ในชื่อสินค้าเฉย ๆ (`...Plus (500)`) ซึ่งคนอ่านออกแต่ระบบ
 * อ่านไม่ออก คนรับของคืนจึงต้องหารในหัวทุกครั้ง และหารพลาดครั้งเดียวคือคืนเงิน
 * ผิดกับสต็อกผิดพร้อมกัน
 *
 * หน่วยที่ระบบเก็บยังเป็นหน่วยที่ขาย (ม้วน) เหมือนเดิมทุกที่ ตารางฟุตเป็นแค่
 * วิธีกรอก ไม่ใช่หน่วยใหม่ที่เงิน สต็อก หรือเอกสารต้องเรียนรู้ ไฟล์นี้จึงมีแต่
 * การแปลงไปกลับ ไม่มีใครเก็บผลลัพธ์ของมันไว้เป็นข้อมูลอีกชุด
 */

/** เท่าที่การแปลงต้องรู้จากสินค้าหนึ่งตัว. */
export type UnitSized = {
  /** ชื่อสินค้า — ร้านเขียนขนาดม้วนไว้ท้ายชื่อในวงเล็บ เช่น `... 40% (250)`. */
  name?: string;
  /** ชนิดสินค้า — ด่านที่กันไม่ให้เลขท้ายชื่อของสินค้าอื่นถูกอ่านเป็นตารางฟุต. */
  category?: string;
  /** จำนวนหน่วยย่อยใน 1 หน่วยที่ขาย — 0 หรือไม่ได้ตั้ง = ไม่ได้ระบุ. */
  unitSize?: number;
  /** ชื่อหน่วยย่อย เช่น ตร.ฟ. */
  unitLabel?: string;
};

/** ใช้เมื่อสินค้ามีขนาดต่อหน่วยแต่ไม่ได้ตั้งชื่อหน่วยย่อยไว้. */
export const DEFAULT_UNIT_LABEL = 'หน่วยย่อย';

/** หน่วยที่ฟิล์มวัดกันจริงในร้าน — เลขท้ายชื่อสินค้าหมายถึงหน่วยนี้. */
export const FILM_SUB_UNIT = 'ตร.ฟ.';

/*
  เลขในวงเล็บ "ท้ายชื่อ" เท่านั้น.

  ชื่อจริงที่ร้านใช้คือ `(ม้วน) ฟิล์ม super nano ceramic 40% (250)` ซึ่งมีวงเล็บ
  สองคู่และมีเลข 40 ลอยอยู่กลางชื่อ ตัวที่หมายถึงขนาดม้วนคือคู่สุดท้ายที่ข้างใน
  เป็นตัวเลขล้วน — ผูกไว้กับท้ายสตริงจึงไม่ไปหยิบ `(ม้วน)` หรือ `40%` มาแทน
*/
const NAME_SIZE = /\(\s*([\d,]+(?:\.\d+)?)\s*\)\s*$/;

/**
 * ฟิล์มเท่านั้น — เลขท้ายชื่อสินค้าอื่นไม่ได้แปลว่าตารางฟุต.
 *
 * "ลำโพงคู่ JBL Stage (2)" จะกลายเป็นม้วนละ 2 ตารางฟุต ถ้าไม่มีด่านนี้ และ
 * การคืนลำโพงหนึ่งคู่จะถูกคิดเป็นการคืน 0.5 ชิ้น ธรรมเนียมเขียนขนาดไว้ท้ายชื่อ
 * เป็นของหมวดฟิล์ม ไม่ใช่ของทั้งทะเบียนสินค้า
 */
function isFilm(item: UnitSized | null | undefined): boolean {
  return (item?.category ?? '').includes('ฟิล์ม');
}

/**
 * ขนาดม้วนที่เขียนไว้ท้ายชื่อสินค้า (ร้านชี้ให้ดู 7 พ.ย. 2569).
 *
 * ร้านเขียนไว้แบบนี้อยู่แล้วทุกตัว — `... 40% (250)` คือม้วนละ 250 ตารางฟุต
 * ซึ่งแปลว่าความรู้นี้ไม่ได้หายไปไหน มันอยู่ในที่ที่คนอ่านออกแต่ระบบอ่านไม่ออก
 * การอ่านมันจึงดีกว่าให้ไปไล่กรอกใหม่ทีละตัวใน 78 รายการ
 */
export function unitSizeFromName(name: string | null | undefined): number {
  const m = NAME_SIZE.exec((name ?? '').trim());
  if (!m) return 0;
  const n = Number(m[1].replace(/,/g, ''));
  return Number.isFinite(n) && n > 0 ? n : 0;
}

/**
 * ขนาดต่อหน่วยที่ใช้หารได้จริง — ไม่ใช่แค่ค่าที่เก็บไว้.
 *
 * 0 กับ ไม่ได้ตั้ง กับ ค่าพัง (NaN จากช่องกรอกที่ว่าง) มีความหมายเดียวกันคือ
 * "ไม่รู้ว่าม้วนละเท่าไหร่" และต้องนำไปสู่พฤติกรรมเดียวกัน คือถามเป็นสัดส่วน
 * ของหน่วยที่ขายเหมือนก่อนมี 0088 ไม่ใช่หารด้วยศูนย์แล้วได้ Infinity
 *
 * ค่าที่กรอกไว้ชนะชื่อสินค้าเสมอ — ชื่อเป็นค่าตั้งต้นที่อ่านได้ฟรี ส่วนช่อง
 * กรอกคือที่ที่ร้านแก้เมื่อชื่อไม่ตรงความจริง ถ้าชื่อชนะ การแก้จะไม่มีผล
 */
export function unitSizeOf(item: UnitSized | null | undefined): number {
  const n = Number(item?.unitSize);
  if (Number.isFinite(n) && n > 0) return n;
  return isFilm(item) ? unitSizeFromName(item?.name) : 0;
}

/** มีขนาดต่อหน่วยให้หารไหม — เงื่อนไขเดียวที่ฝั่ง UI ควรถาม. */
export function hasUnitSize(item: UnitSized | null | undefined): boolean {
  return unitSizeOf(item) > 0;
}

/**
 * ชื่อหน่วยย่อยที่เอาไปแปะข้างตัวเลขได้.
 *
 * ขนาดเปล่า ๆ ไม่มีหน่วยกำกับ อ่านไม่ได้ว่า 500 คืออะไร — คำสำรองจึงเป็นคำ
 * กลาง ๆ ที่ยังอ่านได้ ดีกว่าช่องกรอกที่ไม่บอกว่ากรอกอะไรลงไป
 */
export function unitLabelOf(item: UnitSized | null | undefined): string {
  const explicit = (item?.unitLabel ?? '').trim();
  if (explicit) return explicit;
  // ฟิล์มวัดเป็นตารางฟุตเสมอในร้านนี้ — เลขท้ายชื่อสินค้าก็หมายถึงหน่วยนี้
  return isFilm(item) ? FILM_SUB_UNIT : DEFAULT_UNIT_LABEL;
}

/**
 * ปัดทศนิยม เพื่อให้ตัวเลขที่พิมพ์เข้าไป กลับมาหน้าตาเดิม.
 *
 * ช่อง "คืนมากี่ตารางฟุต" แสดงค่าที่คำนวณกลับจาก qty ที่เก็บไว้ ถ้าไม่ปัด
 * 100 ÷ 350 × 350 จะกลับมาเป็น 99.99999999999999 ในช่องที่คนเพิ่งพิมพ์ 100 ลงไป
 */
export function roundTo(n: number, dp = 4): number {
  const f = 10 ** dp;
  return Math.round(n * f) / f;
}

/** คืนมากี่หน่วยย่อย → กี่หน่วยที่ขาย. 300 ตร.ฟ. ม้วนละ 500 = 0.6 ม้วน. */
export function toSellingUnits(subUnits: number, unitSize: number): number {
  if (!(unitSize > 0)) return subUnits;
  return subUnits / unitSize;
}

/** กี่หน่วยที่ขาย → กี่หน่วยย่อย ซึ่งเป็นตัวเลขที่คนกรอกไว้แต่แรก. */
export function toSubUnits(qty: number, unitSize: number): number {
  if (!(unitSize > 0)) return qty;
  return roundTo(qty * unitSize);
}
