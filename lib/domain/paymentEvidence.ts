/**
 * เงินที่รับแล้วแต่ไม่มีหลักฐานแนบ (ร้านขอ 9 ต.ค. 2569).
 *
 * "ป้องกันการลืม และช่วยให้ตรวจสอบย้อนหลังได้สะดวก" — ช่องแนบสลิปมีมาตั้งแต่
 * 0018 แต่ไม่มีอะไรบอกว่าแถวไหนยังว่าง คนกรอกยอดแล้วตั้งใจจะแนบทีหลังจึงลืมได้
 * ฟรี ๆ และคนที่มาไล่ตรวจเดือนถัดไปต้องเปิดใบงานทีละใบถึงจะรู้
 *
 * กติกาอยู่ที่เดียว เพราะมันถูกถามจากสองที่ที่เห็นคนละมุม: ในใบงานถามว่า
 * "แถวนี้ขาดไหม" ส่วนในรายการใบงานถามว่า "ใบนี้มีแถวที่ขาดไหม" ถ้าสองหน้าตอบ
 * ไม่ตรงกัน ป้ายก็เชื่อไม่ได้ทั้งคู่
 */

/** พอสำหรับตัดสิน — ทั้งใบงานและรายการใบงานส่งมาได้โดยไม่ต้องโหลดทั้งแถว. */
export type PaymentForEvidence = {
  amount: number | string;
  attachments?: string[] | null;
};

/**
 * แถวนี้รับเงินไว้จริงแต่ไม่มีไฟล์แนบ.
 *
 * ยอด 0 ไม่นับ: ฟอร์มเปิดแถวเปล่าไว้ให้กรอก และแถวที่ยังไม่มีตัวเลขก็ยังไม่ใช่
 * การรับเงิน การเตือนตั้งแต่แถวยังว่างคือการเตือนที่ขึ้นก่อนมีอะไรให้ลืม
 *
 * ยอดติดลบนับด้วย — การคืนเงินก็ควรมีหลักฐานเหมือนกัน และที่สำคัญกว่านั้นคือ
 * มันไม่ใช่ศูนย์ แปลว่ามีคนตั้งใจใส่ตัวเลขนั้นลงไป
 */
export function missingEvidence(p: PaymentForEvidence): boolean {
  return Number(p.amount || 0) !== 0 && (p.attachments?.length ?? 0) === 0;
}

/** กี่แถวที่ขาดหลักฐาน — ใช้บอกจำนวนบนป้าย. */
export function countMissingEvidence(payments: readonly PaymentForEvidence[]): number {
  return payments.filter(missingEvidence).length;
}

/** ใบนี้มีแถวที่ขาดหลักฐานไหม — คำถามของรายการใบงาน. */
export function hasMissingEvidence(payments: readonly PaymentForEvidence[]): boolean {
  return payments.some(missingEvidence);
}
