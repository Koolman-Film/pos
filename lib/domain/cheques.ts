/**
 * เช็คที่รับมาแล้ว แต่ยังขึ้นเงินไม่ได้ — กฎกลางที่ทุกหน้าจอใช้ร่วมกัน.
 *
 * เช็คไม่ใช่เงิน จนกว่าจะถึงวันที่หน้าเช็คและมีคนเอาไปขึ้น ร้านขายส่งรับเช็ค
 * ลงวันที่ล่วงหน้าเป็นปกติ จึงมีกระดาษกองหนึ่งอยู่ในมือเสมอ ที่เป็นสิทธิ์ใน
 * เงินก้อนหนึ่ง แต่ยังไม่ใช่ยอดคงเหลือของบัญชีไหน
 *
 * คำถามสองข้อที่ต้องตอบได้ และสำคัญกว่ายอดรวมที่มันประกอบขึ้นมา:
 *
 *   - เดือนหน้าจะมีเงินเข้าเท่าไหร่ — อะไรกำลังจะมา และมาเมื่อไหร่
 *   - ใบไหนเลยกำหนดแล้วยังไม่ยืนยัน — ใบที่ต้องมีคนตามแล้ว
 *
 * ข้อหลังคือเหตุผลที่ไฟล์นี้มีอยู่ เช็คที่ถึงกำหนดไปแล้วเมื่อสัปดาห์ก่อนแต่ไม่
 * เคยถูกยืนยัน คือเงินที่ไม่มีใครเอาไปเข้าบัญชี หรือเช็คที่เด้งโดยไม่มีใคร
 * บันทึก — ทั้งสองทางมันหายไปจากทุกหน้าจอ เพราะเงินที่ไม่ถูกนับ ทำให้ลูกค้า
 * ดูเหมือนแค่คนจ่ายช้า
 */

/** เท่าที่กฎนี้ต้องรู้ — ฝั่งที่เรียกใช้เติมฟิลด์ของตัวเองมาได้ตามต้องการ. */
export type DatedClaim = {
  amount: number;
  /**
   * วันที่ที่คาดว่าเงินจะเข้า — วันที่หน้าเช็ค หรือวันที่รับเงินไว้เมื่อไม่มี
   * เช็คอยู่เบื้องหลัง (เงินสดที่แจ้งแล้วแต่ยังไม่มีใครนับ)
   */
  due: string;
};

export type Pending<T> = T & {
  /** เลยกำหนดแล้วแต่ยังไม่ยืนยัน — ใบที่ต้องตาม. */
  overdue: boolean;
};

export type PendingSummary<T> = {
  rows: Pending<T>[];
  total: number;
  /** ส่วนที่เลยวันที่หน้าเช็คมาแล้ว — ยอดที่ต้องตามวันนี้. */
  overdueTotal: number;
  /** ส่วนที่ยังไม่ถึงวันที่หน้าเช็ค — เงินที่กำลังจะเข้า ไม่ใช่เงินที่หาย. */
  upcomingTotal: number;
};

/**
 * `today` ถูกส่งเข้ามา ไม่ได้อ่านจากนาฬิกาเอง เพื่อให้ผู้เรียกปักเขตเวลาไว้ที่
 * เดียว (`todayValue()`, Asia/Bangkok) แทนที่ไฟล์นี้จะเดา ทั้งสองวันเป็น
 * `YYYY-MM-DD` ซึ่งเทียบกันแบบ string ได้ถูกต้อง
 */
export function summarisePendingCheques<T extends DatedClaim>(
  rows: T[],
  today: string,
): PendingSummary<T> {
  const marked = rows.map((r) => ({
    ...r,
    // ใบที่ไม่มีวันที่เลย ไม่นับว่าเลยกำหนด — มันคือใบที่ไม่ได้ลงวันที่ไว้ การ
    // เรียกมันว่าสายจะส่งคนไปตามเช็คที่อาจยังไม่ถึงกำหนดด้วยซ้ำ
    overdue: !!r.due && r.due < today,
  }));
  // เรียงวันที่ใกล้สุดก่อน ซึ่งดันทุกใบที่เลยกำหนดขึ้นไปกองบนสุดเอง ส่วนใบที่
  // ไม่มีวันที่ไปอยู่ท้ายสุด: มันไม่ได้อ้างว่าเงินจะเข้าเมื่อไหร่
  marked.sort((a, b) => (a.due || '9999-12-31').localeCompare(b.due || '9999-12-31'));
  return {
    rows: marked,
    total: marked.reduce((n, r) => n + r.amount, 0),
    overdueTotal: marked.reduce((n, r) => n + (r.overdue ? r.amount : 0), 0),
    upcomingTotal: marked.reduce((n, r) => n + (r.overdue ? 0 : r.amount), 0),
  };
}
