/** รุ่นล่าสุดที่โค้ดชุดนี้เป็นอยู่. */
export const CURRENT_RELEASE = RELEASES.reduce((max, r) => Math.max(max, r.no), 0);

/**
 * เรื่องที่คนนี้ควรได้ยิน จากรุ่นที่ยังไม่ได้อ่าน.
 *
 * กรองด้วยสิทธิ์รายเมนูที่มีอยู่แล้ว หลักเดียวกับกระดิ่ง: เห็นเฉพาะเรื่องที่
 * เกี่ยวกับงานที่ตัวเองทำได้ ถ้าไม่กรอง หัวหน้าช่างฟิล์มจะได้อ่านเรื่องคอลัมน์
 * เช็คในรายงานขายส่งทุกครั้งที่อัปเดต แล้วสัปดาห์ที่สามเขาจะเลิกอ่านทั้งหมด
 * รวมถึงเรื่องที่เป็นของเขาจริง ๆ
 *
 * รุ่นที่ไม่เหลือเรื่องของคนนี้เลย ถูกตัดทิ้งทั้งรุ่น ไม่ใช่โชว์หัวข้อรุ่นเปล่า ๆ
 */
export function visibleReleases(
  hasNav: (key: string) => boolean,
  { since = 0, releases = RELEASES }: { since?: number; releases?: Release[] } = {},
): Release[] {
  return releases
    .filter((r) => r.no > since)
    .map((r) => ({ ...r, notes: r.notes.filter((n) => !n.nav?.length || n.nav.some(hasNav)) }))
    .filter((r) => r.notes.length > 0)
    .sort((a, b) => b.no - a.no);
}

/** จำนวนเรื่องที่คนนี้ยังไม่ได้อ่าน — ตัวเลขบนจุดสี. */
export function unreadCount(hasNav: (key: string) => boolean, since: number): number {
  return visibleReleases(hasNav, { since }).reduce((n, r) => n + r.notes.length, 0);
}
