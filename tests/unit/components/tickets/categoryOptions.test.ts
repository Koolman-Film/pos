import { describe, it, expect } from 'vitest';

import { sellableCategories } from '@/components/tickets/categoryOptions';

/**
 * ชนิดสินค้าใน Book งาน = ชนิดที่มีของให้ขายจริง (ร้านแจ้ง 27 พ.ย. 2569).
 *
 * ในระบบจริง ช่องชนิดสินค้ามี 14 ชนิด แต่สต็อกมีสินค้าอยู่จริงแค่ 12 — สปอยเลอร์
 * ประกัน และหน้ากาก ค้างอยู่ในรายการตัวเลือกจากตอนตั้งระบบ เลือกแล้วช่องสินค้า
 * ข้างล่างว่างเปล่า ไม่มีอะไรให้กรอกต่อ และไม่มีอะไรบอกว่าทำไม
 */
const stock = (...cats: string[]) => cats.map((category) => ({ category }));

const MANAGED = ['ฟิล์มกรองแสง', 'ฟิล์มกันรอย', 'สปอยเลอร์', 'ประกัน', 'เครื่องเสียง'];

describe('ชนิดสินค้าที่เลือกได้ในใบงาน', () => {
  it('ชนิดที่ไม่มีสินค้าสักตัว ไม่อยู่ในรายการ', () => {
    const out = sellableCategories(MANAGED, stock('ฟิล์มกรองแสง', 'เครื่องเสียง'));
    expect(out).toEqual(['ฟิล์มกรองแสง', 'เครื่องเสียง']);
  });

  it('เรียงตามลำดับที่ร้านตั้งไว้ ไม่ใช่ตามลำดับสินค้าในสต็อก', () => {
    // คนจำตำแหน่งในรายการได้ การสลับที่ทำให้ต้องอ่านใหม่ทุกครั้ง
    const out = sellableCategories(MANAGED, stock('เครื่องเสียง', 'ฟิล์มกันรอย', 'ฟิล์มกรองแสง'));
    expect(out).toEqual(['ฟิล์มกรองแสง', 'ฟิล์มกันรอย', 'เครื่องเสียง']);
  });

  it('สินค้าหลายตัวในชนิดเดียวกัน ไม่ทำให้ชนิดนั้นขึ้นซ้ำ', () => {
    const out = sellableCategories(MANAGED, stock('ฟิล์มกรองแสง', 'ฟิล์มกรองแสง'));
    expect(out).toEqual(['ฟิล์มกรองแสง']);
  });

  it('ชนิดที่มีของ แต่ไม่มีใครเพิ่มลงรายการตัวเลือก ก็ยังเลือกได้', () => {
    /*
      ขาตรงข้ามของปัญหาเดียวกัน: สินค้าที่นำเข้ามาพร้อมชนิดที่ไม่อยู่ในรายการ
      (เช่น "จอ" จากการนำเข้าหลาย SKU) จะขายไม่ได้เลยถ้ากรองด้วยรายการตัวเลือก
      อย่างเดียว — ของมีอยู่บนชั้นแต่เลือกชนิดของมันไม่ได้
    */
    const out = sellableCategories(MANAGED, stock('ฟิล์มกรองแสง', 'จอ', 'กล้อง'));
    expect(out).toEqual(['ฟิล์มกรองแสง', 'กล้อง', 'จอ']);
  });

  it('ชนิดที่บรรทัดนี้ถืออยู่แล้ว ยังอยู่เสมอ แม้ของจะหมดไปแล้ว', () => {
    /*
      `<select>` ที่ค่าไม่ตรงกับตัวเลือกไหนเลย จะแสดงตัวแรกแทน ใบงานเก่าที่ลง
      ชนิดไว้ว่า "หน้ากาก" จึงจะอ่านว่า "ฟิล์มกรองแสง" ทั้งที่ข้อมูลข้างในยัง
      เป็นอย่างเดิม แล้วบันทึกทับทีเดียวก็เปลี่ยนของจริงไปเลย
    */
    const out = sellableCategories(MANAGED, stock('ฟิล์มกรองแสง'), 'หน้ากาก');
    expect(out).toEqual(['หน้ากาก', 'ฟิล์มกรองแสง']);
  });

  it('ชนิดที่ถืออยู่และยังมีของ ไม่ขึ้นซ้ำสองที่', () => {
    const out = sellableCategories(MANAGED, stock('ฟิล์มกรองแสง'), 'ฟิล์มกรองแสง');
    expect(out).toEqual(['ฟิล์มกรองแสง']);
  });

  it('สต็อกว่างเปล่า ก็ไม่เหลือชนิดให้เลือก', () => {
    // ร้านที่ยังไม่ได้ลงสินค้าเลย — รายการว่างคือความจริง ไม่ใช่ความผิดพลาด
    expect(sellableCategories(MANAGED, [])).toEqual([]);
  });

  it('ชนิดที่เป็นค่าว่างหรือมีแต่ช่องว่าง ไม่นับเป็นชนิด', () => {
    const out = sellableCategories(MANAGED, [
      { category: '' },
      { category: '   ' },
      { category: null },
    ]);
    expect(out).toEqual([]);
  });
});
