import { describe, it, expect } from 'vitest';

import { movesMoney, paidWithoutDate } from '@/lib/domain/expenseMoney';

/**
 * กฎข้อเดียวที่หน้า ค่าใช้จ่าย กับฝั่งการจัดการเงิน/แดชบอร์ด ต้องใช้ร่วมกัน.
 *
 * เดิมแต่ละฝั่งเขียนเงื่อนไขของตัวเอง — ฝั่งหนึ่งถามทั้งสถานะและวันที่จ่าย อีก
 * ฝั่งถามแค่สถานะ — แล้วยอดเงินสดย่อยของบัญชีเดียวกันอ่านได้สองตัวเลข ต่างกัน
 * เท่ากับแถวที่ไม่มีวันที่พอดี (ร้านเจอ 31 ต.ค. 2569)
 */
describe('movesMoney — ค่าใช้จ่ายแถวไหนที่เงินออกไปแล้วจริง', () => {
  it('จ่ายแล้ว และมีวันที่ = นับ', () => {
    expect(movesMoney({ status: 'จ่ายแล้ว', paidAt: '2026-10-31' })).toBe(true);
    // หน้า ค่าใช้จ่าย ถือวันที่เป็น Date กฎต้องไม่สนใจว่าเป็นรูปไหน
    expect(movesMoney({ status: 'จ่ายแล้ว', paidAt: new Date('2026-10-31') })).toBe(true);
  });

  it('ยังไม่จ่าย = ไม่นับ แม้จะมีวันที่', () => {
    // วันที่บนแถว รอจ่าย คือกำหนดจ่าย ไม่ใช่วันที่เงินออก
    expect(movesMoney({ status: 'รอจ่าย', paidAt: '2026-10-31' })).toBe(false);
  });

  it('จ่ายแล้วแต่ไม่มีวันที่ = ไม่นับ และต้องถูกชี้ว่าเป็นแถวที่มีปัญหา', () => {
    const row = { status: 'จ่ายแล้ว', paidAt: null };
    expect(movesMoney(row)).toBe(false);
    expect(paidWithoutDate(row)).toBe(true);
  });

  it('แถวที่ยังไม่จ่าย ไม่ใช่แถวที่มีปัญหา', () => {
    // รอจ่าย ที่ไม่มีวันที่จ่ายคือเรื่องปกติ — มันยังไม่ได้จ่าย
    expect(paidWithoutDate({ status: 'รอจ่าย', paidAt: null })).toBe(false);
  });
});
